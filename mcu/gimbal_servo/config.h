#ifndef CONFIG_H
#define CONFIG_H

#include <stdint.h>

//--------------------------------------------------------------------------
// 舵机总线
//--------------------------------------------------------------------------
#define SERVO_BAUD          115200      // 总线波特率（8N1，半双工单线）

// 云台两个舵机的总线 ID（已与现场实际舵机核对确认）：
//   #000 = 水平 Pan（左右旋转）
//   #001 = 垂直 Tilt（前后倒）
// ID 范围 000..254。
#define SERVO_PAN_ID        0
#define SERVO_TILT_ID       1

// 角度 -> 脉宽映射，与 FPGA 侧 servo_pwm.v 完全一致：
//   pulse_us = 500 + 2*angle，angle 0..1000 -> 500..2500us
// 这里再套一层安全钳位（FPGA 已把角度限在 120..880，此处是双保险）。
#define SERVO_PULSE_MIN     500
#define SERVO_PULSE_MAX     2500

// 移动时间 T（ms）：0 = 舵机全速。K210 例程循环里用 T0000。
#define SERVO_MOVE_TIME_MS  0
// 上电居中指令用较慢的速度，避免复位瞬间舵机猛甩。
#define SERVO_INIT_TIME_MS  500

//--------------------------------------------------------------------------
// MCU 时钟（必须与 TD 里 MCU IP 的配置一致）
//--------------------------------------------------------------------------
// 采用 TD MCU IP 默认标准配置：DPLL 使能，核心 300MHz（AHB 150MHz、timer 100MHz）。
// 若 TD 里改过分频，改这里，并同步改 mcu_servo_subsystem.v 的 MCU_DPLL_BYPASS / AHB_FREQ。
#define CORE_CLOCK_HZ       300000000UL

//--------------------------------------------------------------------------
// fabric AHB 寄存器基地址（MCU 侧访问 FPGA 寄存器的绝对地址）★★
//--------------------------------------------------------------------------
// PH1P35 硬核 MCU 的 fabric 窗口固定在 0x8000_0000（官方 ahb_demo_n 例程确认，
// CHIP=ph1p35；PH1 DDR-PHY MCU 的 APB_BASEADDR 同为 0x8000_0000）。
// MCU 的 AHB 主端口 haddr[30:0] 只有 31 位，会把 bit31 丢掉，所以 FPGA 侧
// ahb_sram_regs 只译码"窗口内偏移"，其 REG_BASE=0x0001_0000 是偏移而非绝对地址。
// 固件这里的绝对基址 = 0x8000_0000 + 0x0001_0000 = 0x8001_0000。
// 寄存器绝对地址 = FABRIC_REG_BASE + 偏移（reg[8..11] @ +0x20/0x24/0x28/0x2C）。
#define FABRIC_REG_BASE     0x80010000UL

// 寄存器偏移（相对 FABRIC_REG_BASE，对应 ahb_sram_regs 的 reg[8..11]）
#define REG_PAN_OFFSET      0x20        // reg[8]  = 水平角 [15:0]
#define REG_TILT_OFFSET     0x24        // reg[9]  = 垂直角 [15:0]
#define REG_STATUS_OFFSET   0x28        // reg[10] = bit0 车牌有效, bit1 云台锁定
#define REG_FRAME_OFFSET    0x2C        // reg[11] = 帧计数器低 16 位

//--------------------------------------------------------------------------
// 主循环
//--------------------------------------------------------------------------
// 每 20ms 发一帧（50Hz），与 v1.15 servo_pwm 的 20ms 载波一致。
#define SERVO_UPDATE_PERIOD_MS  20

#endif
