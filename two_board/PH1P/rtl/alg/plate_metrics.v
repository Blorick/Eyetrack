//=============================================================================
//  plate_metrics  --  车牌的真实距离与速度（v1.16 新增，v1.17 修正）
//
//  距离 = 针孔模型，从不变量反推
//  ---------------------------------------------------------------------
//  国标蓝底车牌是**已知尺寸**（440mm x 140mm），所以：
//
//      距离(mm) = 车牌实际宽度(440) x 焦距(像素) / 车牌在画面里的宽度(像素)
//
//  FOCAL_PX 标定：把车牌放在已知距离 D0 处，读 OSD 的 DIS 值 D_read，则
//      FOCAL_PX_new = FOCAL_PX_old * D0 / D_read
//
//  ★ 2026-10-06 上板实测标定（当前参数就是这一组）
//  ---------------------------------------------------------------------
//  被拍物体是**手机模拟的车牌，实际 68mm x 28mm**（不是国标 440mm！）
//  实测：DIS 读 527 时实际距离 300mm
//      1) 反推画面宽度：PLW = 440 * 455 / 527 ≈ 380 px
//      2) 求焦距：      F = PLW * 距离 / 实际宽 = 380 * 300 / 68 = 1676 px
//      3) 验证：        DIS = 68 * 1676 / 380 = 300mm ✓
//
//  ★★ 概念上必须分清（"规范"的关键）
//      PLATE_W_MM = **被拍物体的真实宽度**，随物体而变
//      FOCAL_PX   = **摄像头的焦距（像素）**，是相机属性，与物体无关
//    所以以后换回国标蓝牌（440mm x 140mm），**只把 PLATE_W_MM 改成 440，
//    FOCAL_PX 保持 1676 不动**。
//    交叉验证：焦距 1676 对应水平视场角 2*atan(640/1676) = 41.6°，是常见镜头；
//    而最初默认的 455 对应 109° 超广角，明显不合理（当时没有标定数据）。
//
//  ★ 顺带说明：本模块**只用宽度**反推距离。宽度方向基本不受俯仰透视影响，
//    比用高度稳；而且被拍物件的长宽比只要落在 plate_detect 的 2:1~5:1
//    合法性区间内就行（68:28 = 2.43:1 ✓ 国标 440:140 = 3.14:1 ✓）。
//
//  ★ v1.17 修的三处（上板"距离卡住不变 / 速度不稳"）
//  =====================================================================
//  [1] **乘法位宽截断**（距离卡住的头号嫌疑）
//      Verilog 赋值语句里的乘法按**左值宽度**计算，不是操作数宽度之和：
//          wire [19:0] d = (S_qt[15:0] * FOCAL_PX[19:0]) >> 10;
//      左值 20 位 -> 乘法就在 20 位里做 -> 高位丢掉 -> 结果变垃圾。
//      现在改成 wire [39:0] 中间结果，全宽乘完再移位。
//      速度那处更严重：路径 x 比例 之后还要 x61，值可达 7e10（37 位），
//      原来用 36 位装必然溢出。现在统一 40 位。
//
//  [2] **速度不稳**：比例(mm/px)原来用**瞬时**车牌宽度，而宽度逐帧在抖，
//      速度读数就跟着跳。现在先把宽度做 IIR 平滑，再用平滑值算比例。
//
//  [3] 输出 **O_w_px（平滑后的车牌宽度）**，直接显示到 OSD 的 PLW 行，
//      用来判断"距离不变"到底出在检测（宽度本来就不变）还是出在计算。
//
//  速度为什么用 32 帧窗口
//  ---------------------------------------------------------------------
//  逐帧位移只有几个像素，直接 x60.6 得到的是噪声。窗口累加的是**路径长度**，
//  所以得到的是"窗口平均速度"，约 0.5 秒更新一次。
//  **窗口每帧都推进**（v1.14 的 bug 是只在检测到目标的帧才推进，实际检测
//  断续 -> 窗口永远填不满 -> 速度恒为 0）。目标短暂丢失时保持上一个读数。
//
//  除法：被除数是编译期常量，用移位-试减，19 拍，0 DSP。
//=============================================================================
module plate_metrics #(
    parameter integer IMG_W      = 1280,
    parameter integer IMG_H      = 720,
    parameter [15:0]  PLATE_W_MM = 16'd68,    // ★ 被拍物体真实宽度（手机模拟车牌 68mm）
    parameter [15:0]  FOCAL_PX   = 16'd1676,  // ★ 摄像头焦距（像素），2026-10-06 标定
    parameter [5:0]   SPD_WIN    = 6'd32,     // 速度窗口（帧），2 的幂
    parameter [7:0]   LOST_MAX   = 8'd45,     // 丢失多少帧后速度归零
    parameter [12:0]  DISP_DZ    = 13'd3,     // 单帧位移死区（像素），抑制抖动
    parameter [13:0]  JUMP_MAX   = 14'd120,   // 超过此位移判为**框跳变**，不计入路径
    //---- v1.15 新增：带符号速度（云台超前补偿用）----
    parameter [3:0]   V_IIR_SHIFT   = 4'd3,   // 跟丢了/正常跟踪时，带符号速度的 IIR 系数
    parameter [3:0]   V_DECAY_SHIFT = 4'd5    // 目标丢失期间，带符号速度的衰减系数
)(
    input  wire        I_clk,           // HDMI 像素时钟
    input  wire        I_rst_n,
    input  wire        I_frame,         // 来自 plate_detect.O_frame（每帧 1 拍）
    input  wire        I_valid,         // 来自 plate_detect.O_valid（本帧有车牌）
    input  wire [11:0] I_x0,
    input  wire [11:0] I_y0,
    input  wire [11:0] I_x1,
    input  wire [11:0] I_y1,

    output reg  [19:0] O_dist_mm,       // 真实距离（毫米）
    output reg  [19:0] O_speed_mmps,    // 速度（毫米/秒）
    output reg  [11:0] O_w_px,          // 车牌宽度（像素，平滑后）—— 标定/诊断用
    output reg  [11:0] O_cx, O_cy,      // 车牌中心
    output reg  [7:0]  O_state,         // 0=无目标 1=跟踪 2=保持
    output reg         O_valid,

    //---- v1.15 新增：带符号速度，像素/帧，Q3 定点 ----
    //   v1.16 原来的 O_speed_mmps 累加的是"路径长度"（八边形距离度量），
    //   只有大小、没有方向，云台没法用它做超前补偿。
    //   这两个输出是**逐轴带符号**的，专门给 gimbal_ctrl 用。
    //   单位：像素/帧（不是毫米/秒），因为云台要的直接就是像素超前量；
    //   换算成角度的系数是常数 1/FOCAL_PX，已经在云台那边体现。
    output reg signed [15:0] O_vx_q3,
    output reg signed [15:0] O_vy_q3
);

    //-------------------------------------------------------------------------
    // 0) 除法常量：被除数 = PLATE_W_MM << 10
    //    商 = (440<<10) / w_px = "毫米每像素 x 1024"（Q10）
    //-------------------------------------------------------------------------
    localparam [24:0] DIV_C = {9'd0, PLATE_W_MM} << 10;
    localparam [4:0]  DIVN  = 5'd19;      // 440<<10 = 450560 < 2^19

    // ★ 除法器必须把被除数**预移到最高位**：
    //   移位器是从 S_sr[24] 逐位取出被除数的，而 DIV_C 的最高位在 bit18，
    //   直接装进去的话前 6 拍取到的全是 0，19 拍里只有 13 拍取到真实数据，
    //   等价于被除数右移 6 位 -> 商小了 64 倍。
    //   上板现象就是"PLW 会变、DIS 却几乎不动，卡在 10 附近"。
    localparam [24:0] DIV_INIT = DIV_C << 6;

    //-------------------------------------------------------------------------
    // 1) 原始宽度与中心
    //-------------------------------------------------------------------------
    wire [12:0] W_wraw = {1'b0, I_x1} - {1'b0, I_x0} + 13'd1;
    wire [11:0] W_cx   = ({1'b0, I_x0} + {1'b0, I_x1}) >> 1;
    wire [11:0] W_cy   = ({1'b0, I_y0} + {1'b0, I_y1}) >> 1;

    //  宽度 IIR（8 倍定点）：wf <= wf + (w*8 - wf)>>3
    reg  [15:0] S_wf;
    wire [15:0] W_w8    = {W_wraw[11:0], 3'b000};
    wire [12:0] W_wsm   = S_wf[15:3];                  // 平滑后的整数宽度
    wire [12:0] W_den   = (W_wsm < 13'd16) ? 13'd16 : W_wsm;
    wire        W_first = (S_wf == 16'd0);

    //-------------------------------------------------------------------------
    // 2) 移位-试减除法器（19 拍，被除数是编译期常量）
    //-------------------------------------------------------------------------
    reg  [24:0] S_sr;
    reg  [12:0] S_rm;
    reg  [15:0] S_qt;                   // 毫米每像素 x1024
    reg  [4:0]  S_di;

    wire        W_bit = S_sr[24];
    wire [13:0] W_rm2 = {S_rm, W_bit};
    wire        W_ge  = (W_rm2 >= {1'b0, W_den});

    //-------------------------------------------------------------------------
    // 3) 路径 / 窗口 / 丢失保持
    //-------------------------------------------------------------------------
    reg [11:0] S_pcx, S_pcy;
    reg        S_have_prev;
    reg [7:0]  S_lost;
    reg [16:0] S_path;
    reg [5:0]  S_win;
    reg [19:0] S_dist_f;

    wire [12:0] W_dx  = (W_cx >= S_pcx) ? ({1'b0,W_cx} - {1'b0,S_pcx}) : ({1'b0,S_pcx} - {1'b0,W_cx});
    wire [12:0] W_dy  = (W_cy >= S_pcy) ? ({1'b0,W_cy} - {1'b0,S_pcy}) : ({1'b0,S_pcy} - {1'b0,W_cy});
    wire [12:0] W_dmx = (W_dx > W_dy) ? W_dx : W_dy;
    wire [12:0] W_dmn = (W_dx > W_dy) ? W_dy : W_dx;
    wire [13:0] W_disp= {1'b0, W_dmx} + {2'b0, W_dmn[12:1]};

    //-------------------------------------------------------------------------
    // 4) 换算（★ 全部用 40 位中间结果，避免赋值上下文把乘法压窄）
    //
    //  ★ v1.15：把乘法**打一拍流水**
    //    v1.16/v1.17 里这两级乘法是纯组合的：
    //        S_qt ──40位乘法──>移位──>比较──>IIR──>寄存器
    //    这是显示域最长的一条路（v1.17 的 HDMI 域余量被它压到 +0.201ns）。
    //    现在改成：
    //        S_qt ─[乘法]─> S_dmul_r / S_smul_r ─[移位/比较/IIR]─> 寄存器
    //    乘法落到 DSP 的输入寄存器上，两级之间被寄存器切开。
    //    代价：ST_CALC 之后多等一拍（每帧一次，对 60Hz 完全无影响）。
    //-------------------------------------------------------------------------
    //  距离 = (毫米每像素Q10 x 焦距) >> 10  <= 28160*65535 = 1.8e9 (31 位)
    //  速度(mm/s) = 路径(px)/窗口(帧) x 60.6(帧/s) x 毫米每像素
    //             = (路径 x 毫米每像素Q10 x 61) >> (5+10)
    //    路径 <= 32*1280 = 40960 (16 位)，比例 <= 28160 (15 位)
    //    积 <= 1.16e9 (31 位)，x61 后 <= 7.1e10 (37 位) —— 所以必须 40 位
    //-------------------------------------------------------------------------
    reg [39:0] S_dmul_r;
    reg [39:0] S_smul_r;

    // ★ 复位必须放在**这个** always 块里。若把 S_dmul_r/S_smul_r 的清零
    //   写进下面状态机那个块，同一个 reg 就被两个 always 块驱动，
    //   TD 直接报 "constantly driven from multiple places" 并把模块变成黑盒。
    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            S_dmul_r <= 40'd0;
            S_smul_r <= 40'd0;
        end
        else begin
            S_dmul_r <= S_qt * {24'd0, FOCAL_PX};
            S_smul_r <= {24'd0, S_path} * {25'd0, S_qt};
        end
    end

    wire [39:0] W_s61  = (S_smul_r << 6) - (S_smul_r << 2) + S_smul_r;   // x61
    wire [24:0] W_sq15 = W_s61[39:15];
    wire [19:0] W_dist_new = (S_dmul_r[29:10] > 20'd9999) ? 20'd9999 : S_dmul_r[29:10];
    wire [19:0] W_spd_new  = (W_sq15      > 25'd9999) ? 20'd9999 : W_sq15[19:0];

    //-------------------------------------------------------------------------
    // 4.5) ★ v1.15 新增：逐轴带符号速度（云台超前补偿的唯一输入）
    //
    //   v1.16 的 W_disp = max(dx,dy) + min(dx,dy)/2 是"八边形距离"，
    //   累加出来只有**大小**没有方向 —— 云台没法用它决定往哪边追。
    //   这里单独做一路**带符号**的逐轴速度，单位 像素/帧，Q3 定点。
    //
    //   ★★ 最容易出错的一点：**丢帧后重捕**
    //      S_pcx/S_pcy 只在检测到时更新。若中间丢了 10 帧又重捕，
    //      dx 是跨 11 帧的累计位移；直接当 1 帧速度用会虚高 11 倍，
    //      超前补偿会把云台直接甩出去。
    //      这里用"只在上一帧也有效（S_lost == 0）时才更新"来彻底规避，
    //      丢帧期间改为缓慢衰减 —— 顺带就把"丢目标滑行"需要的行为做出来了。
    //-------------------------------------------------------------------------
    wire signed [12:0] W_cxs = $signed({1'b0, W_cx});
    wire signed [12:0] W_cys = $signed({1'b0, W_cy});
    wire signed [12:0] W_pxs = $signed({1'b0, S_pcx});
    wire signed [12:0] W_pys = $signed({1'b0, S_pcy});

    wire signed [13:0] W_dxs = W_cxs - W_pxs;
    wire signed [13:0] W_dys = W_cys - W_pys;

    wire signed [13:0] W_dzx = (W_dxs > 14'sd0) ? W_dxs : -W_dxs;
    wire signed [13:0] W_dzy = (W_dys > 14'sd0) ? W_dys : -W_dys;

    wire signed [13:0] W_dz_p = $signed({1'b0, DISP_DZ});
    wire signed [13:0] W_jm_p = $signed({1'b0, JUMP_MAX});

    // 死区内记 0（抖动），超过 JUMP_MAX 也记 0（框跳变），其余原样带符号通过
    wire signed [13:0] W_vkx = ((W_dzx > W_dz_p) && (W_dzx <= W_jm_p)) ? W_dxs : 14'sd0;
    wire signed [13:0] W_vky = ((W_dzy > W_dz_p) && (W_dzy <= W_jm_p)) ? W_dys : 14'sd0;

    wire signed [15:0] W_vkx16 = {{2{W_vkx[13]}}, W_vkx};    // 符号扩展到 16 位
    wire signed [15:0] W_vky16 = {{2{W_vky[13]}}, W_vky};
    wire signed [15:0] W_v8x   = W_vkx16 <<< 3;              // ×8，配合 Q3
    wire signed [15:0] W_v8y   = W_vky16 <<< 3;

    //-------------------------------------------------------------------------
    // 5) 状态机
    //    ST_CALC  只做一件事：等上面那两级乘法流水寄存好
    //    ST_CALC2 才用 S_dmul_r / S_smul_r 做移位、比较、IIR
    //-------------------------------------------------------------------------
    localparam [1:0] ST_IDLE  = 2'd0,
                     ST_DIV   = 2'd1,
                     ST_CALC  = 2'd2,
                     ST_CALC2 = 2'd3;
    reg [1:0] S_st;

    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            S_st         <= ST_IDLE;
            S_sr         <= 25'd0;
            S_rm         <= 13'd0;
            S_qt         <= 16'd0;
            S_di         <= 5'd0;
            S_pcx        <= 12'd0;
            S_pcy        <= 12'd0;
            S_have_prev  <= 1'b0;
            S_lost       <= 8'd0;
            S_path       <= 17'd0;
            S_win        <= 6'd0;
            S_wf         <= 16'd0;
            S_dist_f     <= 20'd0;
            O_dist_mm    <= 20'd0;
            O_speed_mmps <= 20'd0;
            O_w_px       <= 12'd0;
            O_cx         <= 12'd0;
            O_cy         <= 12'd0;
            O_state      <= 8'd0;
            O_valid      <= 1'b0;
            O_vx_q3      <= 16'sd0;
            O_vy_q3      <= 16'sd0;
        end
        else begin
            //---- 除法器（只在 ST_DIV 推进）----
            if(S_st == ST_DIV) begin
                S_sr <= {S_sr[23:0], 1'b0};
                if(W_ge) begin
                    S_rm <= W_rm2[12:0] - {1'b0, W_den};
                    S_qt <= {S_qt[14:0], 1'b1};
                end
                else begin
                    S_rm <= W_rm2[12:0];
                    S_qt <= {S_qt[14:0], 1'b0};
                end
            end

            case(S_st)
            //-------------------------------------------------------------
            ST_IDLE: begin
                if(I_frame) begin
                    // ★ 速度窗口每帧都推进（不管有没有检测到目标）
                    if(S_win == SPD_WIN - 6'd1) begin
                        S_win        <= 6'd0;
                        O_speed_mmps <= W_spd_new;
                        S_path       <= 17'd0;
                    end
                    else begin
                        S_win <= S_win + 6'd1;
                    end

                    //---------------------------------------------------------
                    // ★ v1.15：带符号逐轴速度，**每帧都更新**
                    //   S_lost 这里读的是"本帧之前连续丢了多少帧"：
                    //     == 0 → 上一帧也是有效帧，dx 就是真正的单帧位移，正常 IIR
                    //     >  0 → 中间丢过帧，dx 跨了多帧，**绝不能**当单帧速度用，
                    //            改为缓慢衰减（这同时就是"丢目标滑行"要的行为）
                    //---------------------------------------------------------
                    if(S_lost == 8'd0) begin
                        O_vx_q3 <= O_vx_q3 + ((W_v8x - O_vx_q3) >>> V_IIR_SHIFT);
                        O_vy_q3 <= O_vy_q3 + ((W_v8y - O_vy_q3) >>> V_IIR_SHIFT);
                    end
                    else begin
                        O_vx_q3 <= O_vx_q3 - (O_vx_q3 >>> V_DECAY_SHIFT);
                        O_vy_q3 <= O_vy_q3 - (O_vy_q3 >>> V_DECAY_SHIFT);
                    end

                    if(I_valid) begin
                        //---- 宽度平滑（★ 速度不稳的根因：比例必须用平滑宽度）----
                        if(W_first)         S_wf <= W_w8;
                        else if(W_w8 >= S_wf) S_wf <= S_wf + ((W_w8 - S_wf) >> 3);
                        else                S_wf <= S_wf - ((S_wf - W_w8) >> 3);

                        S_lost      <= 8'd0;
                        O_valid     <= 1'b1;
                        O_state     <= 8'd1;
                        O_w_px      <= W_wsm;
                        O_cx        <= W_cx;
                        O_cy        <= W_cy;
                        // ---- 位移累加：死区 + 跳变剔除 ----
                        //   ★ 上板发现：车牌框本身在抖（检测不稳定），框中心会
                        //     偶尔跳几十上百像素。原来一律累加进路径，于是窗口
                        //     速度被这些假跳变顶得莫名其妙偏大。
                        //   现在分三种情况：
                        //     > JUMP_MAX ：判为框跳变，这一帧不计入路径，
                        //                  只把锚点搬到新位置（避免连续误判）
                        //     <= DISP_DZ ：抖动死区，记 0
                        //     其余       ：正常累加
                        if(S_have_prev) begin
                            if(W_disp > JUMP_MAX) begin
                                S_pcx <= W_cx;
                                S_pcy <= W_cy;
                            end
                            else begin
                                if((W_disp > DISP_DZ) && (S_path < 17'h10000))
                                    S_path <= S_path + {3'd0, W_disp};
                                S_pcx <= W_cx;
                                S_pcy <= W_cy;
                            end
                        end
                        else begin
                            S_pcx <= W_cx;
                            S_pcy <= W_cy;
                        end
                        S_have_prev <= 1'b1;
                        // 启动除法：mmpx = C / 平滑后的宽度
                        //   ★ 预移到最高位（见 DIV_INIT 的注释），否则商小 64 倍
                        S_sr <= DIV_INIT;
                        S_rm <= 13'd0;
                        S_qt <= 16'd0;
                        S_di <= 5'd0;
                        S_st <= ST_DIV;
                    end
                    else begin
                        if(S_lost != 8'hFF) S_lost <= S_lost + 8'd1;
                        if(S_lost >= LOST_MAX) begin
                            O_speed_mmps <= 20'd0;
                            O_state      <= 8'd0;
                            S_win        <= 6'd0;
                            S_path       <= 17'd0;
                            S_have_prev  <= 1'b0;
                            // ★ v1.15：长时间丢失，速度也归零，
                            //   否则云台会拿着一份陈旧速度去做超前补偿
                            O_vx_q3      <= 16'sd0;
                            O_vy_q3      <= 16'sd0;
                        end
                        else begin
                            O_state <= 8'd2;   // 保持中：维持上一个读数
                        end
                    end
                end
            end
            //-------------------------------------------------------------
            ST_DIV: begin
                if(S_di == DIVN - 5'd1) S_st <= ST_CALC;
                else                    S_di <= S_di + 5'd1;
            end
            //-------------------------------------------------------------
            ST_CALC: begin
                // ★ v1.15：本状态只用来等 S_dmul_r / S_smul_r 寄存好。
                //   S_qt 在 ST_DIV 的最后一拍才定型，而乘法流水寄存用的是
                //   **上一拍**的 S_qt，所以必须多等一拍再用，否则距离会用到
                //   "商还差最后一位"的中间值。
                S_st <= ST_CALC2;
            end
            //-------------------------------------------------------------
            ST_CALC2: begin
                if(W_dist_new >= S_dist_f) S_dist_f <= S_dist_f + ((W_dist_new - S_dist_f) >> 3);
                else                       S_dist_f <= S_dist_f - ((S_dist_f - W_dist_new) >> 3);
                O_dist_mm <= S_dist_f;
                S_st      <= ST_IDLE;
            end
            default: S_st <= ST_IDLE;
            endcase
        end
    end

